#!/usr/bin/env python3
"""
Build an MFA-compatible pronunciation dictionary from the project's
output/dictionary.txt by mapping eSpeak General American phones to ARPAbet.

Usage:
    python tools/build_mfa_dictionary.py --output output/mfa_dictionary.txt
"""

import argparse
from pathlib import Path


# Mapping from eSpeak US English phones to MFA's english_us_arpa phone set.
# Stress markers are kept simple: vowels in lexical items get stress 1,
# schwa gets stress 0, r-colored vowels are split into V + R.
ESPEAK_TO_ARPA = {
    # Consonants
    "p": "P",
    "b": "B",
    "t": "T",
    "d": "D",
    "k": "K",
    "g": "G",
    "tS": "CH",
    "dZ": "JH",
    "f": "F",
    "v": "V",
    "T": "TH",
    "D": "DH",
    "s": "S",
    "z": "Z",
    "S": "SH",
    "Z": "ZH",
    "h": "HH",
    "m": "M",
    "n": "N",
    "N": "NG",
    "l": "L",
    "r": "R",
    "w": "W",
    "j": "Y",
    # Vowels
    "i:": "IY1",
    "I": "IH1",
    "E": "EH1",
    "a": "AE1",
    "A:": "AA1",
    "0": "AO1",   # open-mid back rounded, close to LOT/PALM in GA
    "O": "AO1",
    "V": "AH1",
    "U": "UH1",
    "u:": "UW1",
    "@": "AH0",
    "3": "ER0",
    "3:": "ER1",
    "eI": "EY1",
    "aI": "AY1",
    "OI": "OY1",
    "aU": "AW1",
    "oU": "OW1",
    # R-colored vowels
    "A@": "AA1 R",
    "O@": "AO1 R",
    "e@": "EH1 R",
    "i@": "IH1 R",
    "U@": "UH1 R",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build MFA dictionary from eSpeak phone dictionary."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("output/dictionary.txt"),
        help="Path to the eSpeak dictionary generated by generate_recording_script.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("output/mfa_dictionary.txt"),
        help="Where to write the MFA dictionary.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    entries = []
    with args.input.open("r", encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            token = parts[0]
            espeak_phones = parts[1:]

            arpa_phones = []
            for phone in espeak_phones:
                if phone not in ESPEAK_TO_ARPA:
                    raise ValueError(f"No ARPAbet mapping for eSpeak phone: {phone}")
                arpa_phones.extend(ESPEAK_TO_ARPA[phone].split())

            entries.append((token, arpa_phones))

    # Add the carrier word "say".
    entries.insert(0, ("say", ["S", "EY1"]))

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as f:
        for token, phones in entries:
            f.write(f"{token}\t{' '.join(phones)}\n")

    print(f"Wrote {len(entries)} entries to {args.output}")


if __name__ == "__main__":
    main()
